/**
 * AdminRoutines — viewer for routines generated on the customer-facing /routine page.
 * Shows skin profile, picked products + the optional selfie users uploaded.
 */
import React, { useEffect, useState } from 'react';
import axios from 'axios';
import { useNavigate, Link } from 'react-router-dom';
import { ArrowLeft, ImageIcon, Sparkles, Sunrise, Moon, RefreshCw, Leaf, Ban, Star, ShoppingBag } from 'lucide-react';
import { getAdminToken } from '../../utils/adminAuth';

const API = `${process.env.REACT_APP_BACKEND_URL}/api`;

export default function AdminRoutines() {
  const navigate = useNavigate();
  const [routines, setRoutines] = useState([]);
  const [loading, setLoading] = useState(true);
  const [expanded, setExpanded] = useState(null);
  const token = getAdminToken();

  const fetchData = async () => {
    setLoading(true);
    try {
      const r = await axios.get(`${API}/admin/routines`, { headers: { 'X-Admin-Token': token } });
      setRoutines(r.data.routines || []);
    } catch (e) {
      // ignore
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (!token) { navigate('/admin'); return; }
    fetchData();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  return (
    <div className="min-h-screen bg-gray-50 lg:ml-64" data-testid="admin-routines">
      <div className="max-w-5xl mx-auto px-4 py-8">
        <Link to="/admin/dashboard" className="inline-flex items-center gap-1 text-gray-500 hover:text-gray-900 text-sm mb-4">
          <ArrowLeft size={14} /> Back to dashboard
        </Link>
        <div className="flex items-center justify-between mb-5">
          <div>
            <h1 className="text-2xl font-bold text-gray-900">Routine reports</h1>
            <p className="text-sm text-gray-500">{routines.length} routine{routines.length === 1 ? '' : 's'} generated by customers</p>
          </div>
          <button onClick={fetchData} className="p-2 rounded-xl border border-gray-200 hover:bg-white" data-testid="routines-refresh">
            <RefreshCw size={16} className={loading ? 'animate-spin' : ''} />
          </button>
        </div>

        {loading ? (
          <div className="flex items-center justify-center py-20"><RefreshCw className="animate-spin text-green-500" /></div>
        ) : routines.length === 0 ? (
          <div className="bg-white rounded-2xl p-10 text-center border border-gray-100">
            <Sparkles className="w-10 h-10 mx-auto mb-3 text-gray-300" />
            <p className="text-sm text-gray-500">No routines generated yet.</p>
          </div>
        ) : (
          <div className="space-y-3">
            {routines.map(r => {
              const isOpen = expanded === r.id;
              return (
                <div key={r.id} className="bg-white rounded-2xl border border-gray-100 shadow-sm overflow-hidden" data-testid={`routine-${r.id}`}>
                  <button onClick={() => setExpanded(isOpen ? null : r.id)} className="w-full p-4 flex items-center gap-3 text-left">
                    <div className="w-12 h-12 rounded-xl bg-emerald-50 flex items-center justify-center overflow-hidden flex-shrink-0">
                      {r.photo_url || r.photo_data
                        ? <img src={r.photo_url || r.photo_data} alt="" className="w-full h-full object-cover" />
                        : <ImageIcon className="w-5 h-5 text-emerald-400" />}
                    </div>
                    <div className="flex-1 min-w-0">
                      <p className="font-semibold text-gray-900 text-sm truncate">{r.skin_type} · {r.age}{typeof r.skin_score === 'number' ? ` · Score ${r.skin_score}/100` : ''}</p>
                      <p className="text-xs text-gray-500 truncate">
                        {r.email ? <span className="text-emerald-700 font-medium">{r.email} · </span> : null}
                        Concerns: {r.concerns?.join(', ') || '—'}
                      </p>
                    </div>
                    {r.source === 'tracker_scan' && <span className="text-[10px] font-bold uppercase tracking-wide px-2 py-1 rounded-full bg-emerald-50 text-emerald-700 mr-2">AI Scan</span>}
                    <span className="text-[11px] text-gray-400">{new Date(r.created_at).toLocaleString('en-IN', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' })}</span>
                  </button>

                  {isOpen && (
                    <div className="border-t border-gray-100 p-4 bg-gray-50">
                      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                        <div>
                          <h4 className="text-xs font-bold text-amber-700 flex items-center gap-1.5 mb-2"><Sunrise size={12} /> Morning ritual</h4>
                          <ul className="space-y-1 text-xs">
                            {r.am?.map((s, i) => (
                              <li key={`am-${i}`} className="flex items-center gap-2">
                                <span className="text-gray-500 w-20 truncate">{s.slot?.label}</span>
                                <span className="font-medium text-gray-900 truncate">{s.product_name || '—'}</span>
                              </li>
                            ))}
                          </ul>
                        </div>
                        <div>
                          <h4 className="text-xs font-bold text-violet-700 flex items-center gap-1.5 mb-2"><Moon size={12} /> Night ritual</h4>
                          <ul className="space-y-1 text-xs">
                            {r.pm?.map((s, i) => (
                              <li key={`pm-${i}`} className="flex items-center gap-2">
                                <span className="text-gray-500 w-20 truncate">{s.slot?.label}</span>
                                <span className="font-medium text-gray-900 truncate">{s.product_name || '—'}</span>
                              </li>
                            ))}
                          </ul>
                        </div>
                      </div>
                      {/* 3-side face scan (front / left / right) captured during the routine */}
                      {(r.photo_url || r.photo_data || r.photo_left_data || r.photo_right_data) && (
                        <div className="mt-4">
                          <p className="text-xs font-bold text-gray-600 mb-2">Face scan (3 angles)</p>
                          <div className="flex gap-3 flex-wrap">
                            {[
                              { label: 'Front', src: r.photo_url || r.photo_data },
                              { label: 'Left', src: r.photo_left_data },
                              { label: 'Right', src: r.photo_right_data },
                            ].map((s, i) => (
                              <div key={i} className="text-center">
                                <div className="w-28 h-28 rounded-xl ring-1 ring-gray-200 overflow-hidden bg-white flex items-center justify-center">
                                  {s.src
                                    ? <img src={s.src} alt={`${s.label} scan`} className="w-full h-full object-cover" />
                                    : <ImageIcon className="w-5 h-5 text-gray-300" />}
                                </div>
                                <p className="text-[11px] text-gray-500 mt-1">{s.label}</p>
                              </div>
                            ))}
                          </div>
                        </div>
                      )}
                      {Array.isArray(r.specialist_notes) && r.specialist_notes.length > 0 && (
                        <div className="mt-4">
                          <p className="text-xs font-bold text-gray-600 mb-1">Specialist notes</p>
                          <ul className="list-disc list-inside text-xs text-gray-600 space-y-0.5">
                            {r.specialist_notes.slice(0, 6).map((n, i) => <li key={i}>{n}</li>)}
                          </ul>
                        </div>
                      )}
                      {(r.diet?.length || r.control?.length) && (
                        <div className="mt-4 grid grid-cols-1 sm:grid-cols-2 gap-4">
                          {r.diet?.length ? (
                            <div>
                              <h4 className="text-xs font-bold text-emerald-700 flex items-center gap-1.5 mb-2"><Leaf size={12} /> Diet</h4>
                              <ul className="list-disc list-inside text-xs text-gray-600 space-y-0.5">
                                {r.diet.map((d, i) => <li key={i}>{d}</li>)}
                              </ul>
                            </div>
                          ) : null}
                          {r.control?.length ? (
                            <div>
                              <h4 className="text-xs font-bold text-rose-700 flex items-center gap-1.5 mb-2"><Ban size={12} /> What to control / avoid</h4>
                              <ul className="list-disc list-inside text-xs text-gray-600 space-y-0.5">
                                {r.control.map((d, i) => <li key={i}>{d}</li>)}
                              </ul>
                            </div>
                          ) : null}
                        </div>
                      )}
                      {r.weekly?.length ? (
                        <div className="mt-4">
                          <h4 className="text-xs font-bold text-amber-700 flex items-center gap-1.5 mb-2"><Star size={12} /> Weekly treatments</h4>
                          <ul className="list-disc list-inside text-xs text-gray-600 space-y-0.5">
                            {r.weekly.map((d, i) => <li key={i}>{d}</li>)}
                          </ul>
                        </div>
                      ) : null}
                      {r.recommended_products?.length ? (
                        <div className="mt-4">
                          <h4 className="text-xs font-bold text-gray-600 flex items-center gap-1.5 mb-2"><ShoppingBag size={12} /> Recommended products</h4>
                          <div className="flex flex-wrap gap-2">
                            {r.recommended_products.map((p, i) => (
                              <span key={i} className="text-[11px] bg-white border border-gray-200 rounded-lg px-2 py-1 text-gray-700">{p.name}{p.price ? ` · ₹${p.price}` : ''}</span>
                            ))}
                          </div>
                        </div>
                      ) : null}
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
}
